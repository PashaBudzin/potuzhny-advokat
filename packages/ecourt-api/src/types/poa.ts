import type { DictionaryRecord } from "./dictionaries";
import type { DocumentFileDto } from "./documents";

/**
 * Binary flag used by power-of-attorney permissions.
 *
 * `1` means the permission is granted, `0` means it is not.
 */
export type PowerOfAttorneyFlag = 0 | 1 | number;

/**
 * Status of a power of attorney (Статус довіреності).
 *
 * Known identifiers:
 * - `-1` — deleted;
 * - `0` — draft;
 * - `1` — active;
 * - `2` — expired.
 */
export interface PowerOfAttorneyStatus extends DictionaryRecord {
    /** Short description. */
    descr?: string;
}

/**
 * Type of a power of attorney (Тип довіреності).
 *
 * Known identifiers:
 * - `0` — power of attorney;
 * - `1` — order (ордер);
 * - `2` — system power of attorney (extract from the EDR).
 */
export interface PowerOfAttorneyType extends DictionaryRecord {
    /** Short description. */
    descr?: string;
}

/**
 * Scope of a power of attorney (Область дії довіреності).
 *
 * Known identifiers:
 * - `0` — general;
 * - `1` — proceeding;
 * - `2` — case;
 * - `3` — justice type.
 */
export interface PowerOfAttorneyTargetType extends DictionaryRecord {
    /** Short description. */
    descr?: string;
}

/**
 * Scope identifier used by {@link PowerOfAttorney.targetTypeId}.
 */
export type PowerOfAttorneyTargetTypeId = 0 | 1 | 2 | 3 | number;

/**
 * Power of attorney record (Довіреність).
 */
export interface PowerOfAttorney {
    /** eCourt power of attorney identifier. */
    id: string;
    /** Creation date and time (ISO 8601). */
    createdAt?: string;
    /** Tax identifier (RNOKPP) of the user who created the record. */
    createdByCode?: string;
    /** Full name of the user who created the record. */
    createdByName?: string;
    /** Internal identifier of the principal (довіритель). */
    allowedBy?: string;
    /** Tax identifier (RNOKPP/EDRPOU) of the principal. */
    allowedByCode?: string;
    /** Full name or organisation name of the principal. */
    allowedByName?: string;
    /** Internal identifier of the representative (представник). */
    allowedTo?: string;
    /** Tax identifier (RNOKPP) of the representative. */
    allowedToCode: string;
    /** Full name of the representative. */
    allowedToName: string;
    /** Permission to view the principal's documents. */
    allowRead?: PowerOfAttorneyFlag;
    /** Permission to edit the principal's documents. */
    allowEdit?: PowerOfAttorneyFlag;
    /** Permission to submit documents on behalf of the principal. */
    allowCommit?: PowerOfAttorneyFlag;
    /** Permission to submit enforcement documents to the ASVP. */
    allowAsvp?: PowerOfAttorneyFlag;
    /** Permission to delegate the power of attorney (передоручення). */
    allowShare?: PowerOfAttorneyFlag;
    /** Expiration date and time (ISO 8601). Absent for indefinite powers. */
    expirationDate?: string;
    /** Whether the power of attorney has not been revoked. */
    isActive?: boolean;
    /** Additional metadata generated by eCourt. */
    meta?: string;
    /** Power of attorney file metadata. */
    original?: DocumentFileDto;
    /** Identifier of the parent power of attorney for delegated powers. */
    parentId?: string;
    /** Parent power of attorney. Included only with `join=parent`. */
    parent?: PowerOfAttorney;
    /** Status identifier. See {@link PowerOfAttorneyStatus}. */
    statusId?: number;
    /** Status. Included only with `join=status`. */
    status?: PowerOfAttorneyStatus;
    /** Identifier of the target object. */
    targetId?: string;
    /** Target key (case or proceeding number) when `targetId` is unknown. */
    targetKey?: string;
    /** Scope identifier. */
    targetTypeId?: PowerOfAttorneyTargetTypeId;
    /** Scope. Included only with `join=targetType`. */
    targetType?: PowerOfAttorneyTargetType;
    /** Type identifier. See {@link PowerOfAttorneyType}. */
    typeId?: number;
    /** Last update date and time (ISO 8601). */
    updatedAt?: string;
    /** Identifier of the user who last updated the record. */
    updatedBy?: string;
    /** Full name of the user who last updated the record. */
    updatedByName?: string;
}

/**
 * Payload for submitting a power of attorney.
 *
 * The file referenced by {@link original} must be uploaded to the storage
 * first, and the detached signature must be uploaded with
 * `client.storage.uploadSignature`.
 */
export interface PowerOfAttorneyPostDto {
    /** Tax identifier (RNOKPP) of the representative. */
    allowedToCode: string;
    /** Full name of the representative. */
    allowedToName: string;
    /** Permission to view the principal's documents. */
    allowRead?: PowerOfAttorneyFlag;
    /** Permission to edit the principal's documents. */
    allowEdit?: PowerOfAttorneyFlag;
    /** Permission to submit documents on behalf of the principal. */
    allowCommit?: PowerOfAttorneyFlag;
    /** Permission to submit enforcement documents to the ASVP. */
    allowAsvp?: PowerOfAttorneyFlag;
    /** Permission to delegate the power of attorney. */
    allowShare?: PowerOfAttorneyFlag;
    /** Expiration date and time (ISO 8601). Absent for indefinite powers. */
    expirationDate?: string;
    /** Power of attorney file metadata with its detached signature. */
    original: DocumentFileDto;
    /** Identifier of the target object. */
    targetId?: string;
    /** Target key (case or proceeding number) when `targetId` is unknown. */
    targetKey?: string;
    /**
     * Scope identifier.
     *
     * The full data model defines `0` general, `1` proceeding, `2` case,
     * `3` justice type. The example in the SRS swaps case and proceeding, so
     * verify the value against the current API contract.
     */
    targetTypeId?: PowerOfAttorneyTargetTypeId;
    /**
     * Type identifier. The corporate API allows only `0` (power of attorney).
     * Defaults to `0` on the server when omitted.
     */
    typeId?: number;
}
